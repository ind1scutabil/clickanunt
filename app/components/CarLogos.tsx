// Map brand names to logo functions
export function getCarLogoSVG(brandName: string) {
  if (!brandName) return CarLogos.default;
  
  // Comprehensive brand name mapping
  const brandMap: Record<string, keyof typeof CarLogos> = {
    'volkswagen': 'volkswagen',
    'vw': 'volkswagen',
    'bmw': 'bmw',
    'mercedes': 'mercedes',
    'mercedes-benz': 'mercedes',
    'audi': 'audi',
    'porsche': 'porsche',
    'ferrari': 'ferrari',
    'lamborghini': 'lamborghini',
    'ford': 'ford',
    'honda': 'honda',
    'toyota': 'toyota',
    'nissan': 'nissan',
    'mazda': 'mazda',
    'subaru': 'subaru',
    'hyundai': 'hyundai',
    'kia': 'kia',
    'skoda': 'skoda',
    'renault': 'renault',
    'peugeot': 'peugeot',
    'citroen': 'citroen',
    'citroën': 'citroen',
    'dacia': 'dacia',
  };
  
  const normalized = brandName.toLowerCase().trim();
  const key = brandMap[normalized] || normalized.replace(/[^a-z]/g, '');
  
  // Check if we have a specific logo
  if (CarLogos[key as keyof typeof CarLogos]) {
    return CarLogos[key as keyof typeof CarLogos];
  }
  
  // Generate text-based logo badge (Auto1 style - professional)
  const initials = brandName
    .split(/[\s-]/)
    .map(word => word[0])
    .filter(Boolean)
    .slice(0, 2)
    .join('')
    .toUpperCase();
  
  return (
    <svg viewBox="0 0 100 100" xmlns="http://www.w3.org/2000/svg" className="w-full h-full">
      <defs>
        <linearGradient id={`grad-${initials}`} x1="0%" y1="0%" x2="100%" y2="100%">
          <stop offset="0%" style={{ stopColor: '#6366F1', stopOpacity: 1 }} />
          <stop offset="100%" style={{ stopColor: '#8B5CF6', stopOpacity: 1 }} />
        </linearGradient>
      </defs>
      <circle cx="50" cy="50" r="46" fill={`url(#grad-${initials})`} stroke="#7C3AED" strokeWidth="1.5"/>
      <text 
        x="50" 
        y="50" 
        fontSize={initials.length > 1 ? "32" : "42"} 
        fontWeight="700" 
        textAnchor="middle" 
        dominantBaseline="central" 
        fill="white"
        fontFamily="system-ui, -apple-system, sans-serif"
      >
        {initials}
      </text>
    </svg>
  );
}

